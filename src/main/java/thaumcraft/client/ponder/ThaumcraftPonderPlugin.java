package thaumcraft.client.ponder;

import net.createmod.ponder.api.registration.PonderPlugin;
import net.createmod.ponder.api.registration.PonderSceneRegistrationHelper;
import net.createmod.ponder.foundation.PonderIndex;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.registries.DeferredHolder;
import thaumcraft.Thaumcraft;
import thaumcraft.common.config.ConfigBlocks;

/**
 * Ponder tutorials (hold W over an item). Ponder is optional: this class is only touched from
 * {@link #register()}, which ThaumcraftClient calls only when the "ponder" mod is loaded.
 * Scene texts live in en_us.json under thaumcraft.ponder.&lt;scene&gt;.header / text_N.
 */
public class ThaumcraftPonderPlugin implements PonderPlugin {

    public static void register() {
        PonderIndex.addPlugin(new ThaumcraftPonderPlugin());
    }

    @Override
    public String getModId() {
        return Thaumcraft.MODID;
    }

    @Override
    public void registerScenes(PonderSceneRegistrationHelper<ResourceLocation> helper) {
        PonderSceneRegistrationHelper<DeferredHolder<?, ?>> h = helper.withKeyFunction(DeferredHolder::getId);
        // The .nbt files are read from assets/thaumcraft/ponder/<name>.nbt (generated by tools/gen_ponder_nbt.py).
        h.addStoryBoard(ConfigBlocks.crucible, "crucible", ThaumcraftPonderScenes::crucible);
        h.forComponents(ConfigBlocks.infusionMatrix, ConfigBlocks.pedestalArcane, ConfigBlocks.pillarArcane)
                .addStoryBoard("infusion_altar", ThaumcraftPonderScenes::infusionAltar);
        h.forComponents(ConfigBlocks.smelterBasic, ConfigBlocks.alembic, ConfigBlocks.tube, ConfigBlocks.bellows)
                .addStoryBoard("smelting", ThaumcraftPonderScenes::smelting);
    }
}
